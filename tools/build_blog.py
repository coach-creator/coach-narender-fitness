def fill_tokens(template: str, mapping: dict[str, str]) -> str:
    def replace(match: re.Match) -> str:
        key = match.group(1)
        if key not in mapping:
            raise SystemExit(f"unfilled template token: {key}")
        return mapping[key]

    rendered = re.sub(r"@@([A-Z0-9_]+)@@", replace, template)
    leftover = re.findall(r"@@[A-Z0-9_]+@@", rendered)
    if leftover:
        raise SystemExit("unfilled template tokens: " + ", ".join(leftover))
    if not rendered.endswith("\n"):
        rendered += "\n"
    return rendered


