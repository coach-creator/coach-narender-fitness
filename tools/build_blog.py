def split_bilingual(text: str) -> tuple[str, str] | None:
    stripped = text.strip()
    if not stripped or len(stripped) > 420:
        return None
    parts = re.split(r"(?<=[.!?])\s+", stripped)
    if len(parts) < 2:
        return None
    first, rest = parts[0], " ".join(parts[1:]).strip()
    words = re.findall(r"[A-Za-z']+", first.lower())
    if not words or not rest or words[0] in ENGLISH_OPENERS:
        return None
    if sum(1 for word in words if word in HINDI_MARKERS) < 3:
        return None
    if not re.search(r"\b(you|the|a|is|are|to|did|not|in)\b", rest, re.IGNORECASE):
        return None
    return first, rest


def blockquote_html(text: str, out: Path) -> str:
    split = split_bilingual(text)
    if split is None:
        return f"<blockquote><p>{inline(text, out, lazy=True)}</p></blockquote>"
    quote, translation = split
    return (
        "<blockquote>"
        f"<p>{inline(quote, out, lazy=True)}</p>"
        f'<p class="translation">{inline(translation, out, lazy=True)}</p>'
        "</blockquote>"
    )


def markdown_to_html(body: str, out: Path) -> tuple[str, list[tuple[str, str]]]:
    lines = body.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    parts: list[str] = []
    headings: list[tuple[str, str]] = []
    used: set[str] = set()
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.strip():
            index += 1
            continue
        kind = block_kind(line)
        if kind in ("h2", "h3"):
            level = 2 if kind == "h2" else 3
            text = line.strip()[level + 1 :].strip()
            index += 1
            if not text:
                continue
            heading_id = unique_id(plain_text(text), used)
            if kind == "h2":
                headings.append((heading_id, plain_text(text)))
            parts.append(f'<h{level} id="{heading_id}">{inline(text, out, lazy=True)}</h{level}>')
            continue
        if kind == "quote":
            chunks = []
            while index < len(lines) and lines[index].lstrip().startswith(">"):
                chunk = lines[index].lstrip()[1:]
                if chunk.startswith(" "):
                    chunk = chunk[1:]
                chunks.append(chunk.strip())
                index += 1
            parts.append(blockquote_html(" ".join(chunks), out))
            continue
        if kind == "ul":
            items = []
            while index < len(lines) and re.match(r"\s*[-*] ", lines[index]):
                items.append(re.sub(r"^\s*[-*] ", "", lines[index].strip()))
                index += 1
            parts.append("<ul>" + "".join(f"<li>{inline(item, out, lazy=True)}</li>" for item in items) + "</ul>")
            continue
        if kind == "ol":
            items = []
            while index < len(lines) and re.match(r"\s*\d+\. ", lines[index]):
                items.append(re.sub(r"^\s*\d+\. ", "", lines[index].strip()))
                index += 1
            parts.append("<ol>" + "".join(f"<li>{inline(item, out, lazy=True)}</li>" for item in items) + "</ol>")
            continue
        if kind == "table":
            rows = []
            while index < len(lines) and lines[index].lstrip().startswith("|"):
                rows.append(lines[index].strip())
                index += 1
            parts.append(render_table(rows, out))
            continue
        if kind == "image":
            parts.append(f"<figure>{inline(line.strip(), out, lazy=True)}</figure>")
            index += 1
            continue
        chunks = [line.strip()]
        index += 1
        while index < len(lines) and lines[index].strip() and block_kind(lines[index]) == "p":
            chunks.append(lines[index].strip())
            index += 1
        joined = " ".join(chunks)
        if split_bilingual(joined):
            parts.append(blockquote_html(joined, out))
        else:
            parts.append(f"<p>{inline(joined, out, lazy=True)}</p>")
    rendered = "\n".join(parts)
    return mark_medical(rendered), headings


def block_kind(line: str) -> str:
    stripped = line.lstrip()
    if stripped.startswith("### "):
        return "h3"
    if stripped.startswith("## "):
        return "h2"
    if stripped.startswith(">"):
        return "quote"
    if re.match(r"[-*] ", stripped):
        return "ul"
    if re.match(r"\d+\. ", stripped):
        return "ol"
    if stripped.startswith("|"):
        return "table"
    if re.fullmatch(r"!\[[^\]]*\]\([^)\s]+\)", stripped):
        return "image"
    return "p"


def inline(text: str, out: Path, lazy: bool) -> str:
    pattern = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)\)|\[([^\]]+)\]\(([^)\s]+)\)")
    pieces = []
    cursor = 0
    for match in pattern.finditer(text):
        pieces.append(emphasize(text[cursor:match.start()]))
        if match.group(2) is not None and text[match.start():match.start() + 2] == "![":
            pieces.append(image_tag(match.group(1), match.group(2), out, lazy))
        else:
            pieces.append(link_tag(match.group(3), match.group(4)))
        cursor = match.end()
    pieces.append(emphasize(text[cursor:]))
    return "".join(pieces)


def emphasize(text: str) -> str:
    rendered = html.escape(text, quote=False)
    rendered = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", rendered)
    rendered = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", rendered)
    rendered = re.sub(r"(?<![\w])_([^_]+)_(?![\w])", r"<em>\1</em>", rendered)
    return rendered


def link_tag(label: str, href: str) -> str:
    if not safe_url(href):
        return emphasize(label)
    target = absolutize(href)
    return f'<a href="{html.escape(target, quote=True)}">{emphasize(label)}</a>'


def image_tag(alt: str, src: str, out: Path, lazy: bool) -> str:
    source = src if src.startswith(("http://", "https://")) else absolutize(src)
    dims = image_dimensions(source, out)
    size = f' width="{dims[0]}" height="{dims[1]}"' if dims else ""
    loading = ' loading="lazy"' if lazy else ' loading="eager" fetchpriority="high"'
    return (
        f'<img src="{html.escape(source, quote=True)}" alt="{html.escape(alt, quote=True)}"'
        f'{size}{loading} decoding="async">'
    )


def render_table(rows: list[str], out: Path) -> str:
    parsed = []
    for row in rows:
        parsed.append([cell.strip() for cell in row.strip().strip("|").split("|")])
    header = None
    body = parsed
    if len(parsed) >= 2 and all(re.fullmatch(r":?-{3,}:?", cell or "") for cell in parsed[1]):
        header = parsed[0]
        body = parsed[2:]
    parts = ['<div class="table-wrap"><table>']
    if header is not None:
        parts.append("<thead><tr>" + "".join(f"<th>{inline(cell, out, lazy=True)}</th>" for cell in header) + "</tr></thead>")
    parts.append("<tbody>")
    for row in body:
        parts.append("<tr>" + "".join(f"<td>{inline(cell, out, lazy=True)}</td>" for cell in row) + "</tr>")
    parts.append("</tbody></table></div>")
    return "".join(parts)


def medical_label_repeats(text: str) -> bool:
    folded = re.sub(r"[^a-z0-9]+", " ", text.lower())
    return "general education" in folded and "not medical advice" in folded


def mark_medical(rendered: str) -> str:
    medical = load_medical_line()
    needle = re.sub(r"\s+", " ", medical).strip()

    def replace_paragraph(match: re.Match) -> str:
        inner = match.group(1)
        text = html.unescape(re.sub(r"<[^>]+>", "", inner))
        text = re.sub(r"\s+", " ", text).strip()
        if needle and needle in text:
            label = ""
            if not medical_label_repeats(text):
                label = f'<p class="medical-label">{html.escape(MEDICAL_LABEL)}</p>'
            return f'<aside class="medical-note">{label}<p>{inner}</p></aside>'
        return match.group(0)

    rendered = re.sub(r"<p>(.*?)</p>", replace_paragraph, rendered, flags=re.DOTALL)
    rendered = rendered.replace("<blockquote><aside class=\"medical-note\">", "<aside class=\"medical-note\">")
    rendered = rendered.replace("</aside></blockquote>", "</aside>")
    return rendered


def plain_text(text: str) -> str:
    text = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    return re.sub(r"[*_`]", "", text).strip()


def unique_id(text: str, used: set[str]) -> str:
    base = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "section"
    candidate = base
    number = 2
    while candidate in used:
        candidate = f"{base}-{number}"
        number += 1
    used.add(candidate)
    return candidate


def safe_url(url: str) -> bool:
    value = url.strip()
    lowered = value.lower()
    if lowered.startswith(("javascript:", "data:")):
        return False
    return value.startswith(("#", "/", "http://", "https://", "mailto:")) or "://" not in value


def absolutize(url: str) -> str:
    if url.startswith(("http://", "https://", "mailto:", "#", "/")):
        return url
    return "/" + url.lstrip("./")


def image_dimensions(src: str, out: Path) -> tuple[int, int] | None:
    path = locate_asset(src, out)
    if path is None:
        return None
    try:
        data = path.read_bytes()
    except OSError:
        return None
    return sniff_size(data)


def locate_asset(src: str, out: Path) -> Path | None:
    if not src or src.startswith(("http://", "https://")):
        return None
    relative = src.split("?", 1)[0].split("#", 1)[0].lstrip("/")
    if not relative:
        return None
    for base in (out, PREVIEW):
        candidate = base / relative
        if candidate.is_file():
            return candidate
    return None


def sniff_size(data: bytes) -> tuple[int, int] | None:
    if data.startswith(b"\x89PNG\r\n\x1a\n") and len(data) >= 24:
        return int.from_bytes(data[16:20], "big"), int.from_bytes(data[20:24], "big")
    if data.startswith((b"GIF87a", b"GIF89a")) and len(data) >= 10:
        return int.from_bytes(data[6:8], "little"), int.from_bytes(data[8:10], "little")
    if data.startswith(b"\xff\xd8"):
        return jpeg_size(data)
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return webp_size(data)
    return None


def jpeg_size(data: bytes) -> tuple[int, int] | None:
    index = 2
    while index + 1 < len(data):
        if data[index] != 0xFF:
            return None
        while index < len(data) and data[index] == 0xFF:
            index += 1
        if index >= len(data):
            return None
        marker = data[index]
        index += 1
        if marker in (0xD8, 0xD9):
            continue
        if marker == 0xDA or index + 2 > len(data):
            return None
        length = int.from_bytes(data[index:index + 2], "big")
        if length < 2:
            return None
        if marker in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
            if index + 7 > len(data):
                return None
            height = int.from_bytes(data[index + 3:index + 5], "big")
            width = int.from_bytes(data[index + 5:index + 7], "big")
            return width, height
        index += length
    return None


def webp_size(data: bytes) -> tuple[int, int] | None:
    if len(data) < 30:
        return None
    chunk = data[12:16]
    if chunk == b"VP8X":
        return 1 + int.from_bytes(data[24:27], "little"), 1 + int.from_bytes(data[27:30], "little")
    if chunk == b"VP8 ":
        start = data.find(b"\x9d\x01\x2a", 20, 60)
        if start < 0 or start + 7 > len(data):
            return None
        width = int.from_bytes(data[start + 3:start + 5], "little") & 0x3FFF
        height = int.from_bytes(data[start + 5:start + 7], "little") & 0x3FFF
        return width, height
    if chunk == b"VP8L" and len(data) >= 25 and data[20] == 0x2F:
        b0, b1, b2, b3 = data[21], data[22], data[23], data[24]
        width = 1 + (((b1 & 0x3F) << 8) | b0)
        height = 1 + (((b3 & 0x0F) << 10) | (b2 << 2) | ((b1 & 0xC0) >> 6))
        return width, height
    return None


